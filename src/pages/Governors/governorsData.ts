// Helper to compute category distribution counts for Chart canvas
export function getGovernorCategoryCounts(data: GovernorRecord[] = GOVERNORS_DATA) {
  const statusCounts: Record<string, number> = { State: 0, UT: 0 };
  const genderCounts: Record<string, number> = { Male: 0, Female: 0 };
  const religionCounts: Record<string, number> = {};
  const educationCounts: Record<string, number> = {
    'Post-Grad / Ph.D': 0,
    'Law (LL.B)': 0,
    'Graduate (B.A/B.Sc/B.Com)': 0,
    'Others / Diploma': 0,
  };

  data.forEach((gov) => {
    // Status
    if (gov.status === 'UT') statusCounts.UT += 1;
    else statusCounts.State += 1;

    // Gender
    if (gov.gender === 'Female') genderCounts.Female += 1;
    else genderCounts.Male += 1;

    // Religion
    religionCounts[gov.religion] = (religionCounts[gov.religion] || 0) + 1;

    // Education category
    const edu = (gov.highestEducation || '').toLowerCase();
    if (edu.includes('ph.d') || edu.includes('m.a') || edu.includes('m.sc') || edu.includes('m.tech') || edu.includes('m.phil')) {
      educationCounts['Post-Grad / Ph.D'] += 1;
    } else if (edu.includes('ll.b') || edu.includes('law')) {
      educationCounts['Law (LL.B)'] += 1;
    } else if (edu.includes('bachelor') || edu.includes('b.sc') || edu.includes('b.com') || edu.includes('b.a') || edu.includes('b.tech') || edu.includes('b.b.a')) {
      educationCounts['Graduate (B.A/B.Sc/B.Com)'] += 1;
    } else {
      educationCounts['Others / Diploma'] += 1;
    }
  });

  return {
    Status: statusCounts,
    Gender: genderCounts,
    Religion: religionCounts,
    Education: educationCounts,
  };
}

